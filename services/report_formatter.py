    @staticmethod
    def _build_citation_mapping(report: AcademicReport) -> Dict[str, Dict[str, Any]]:
        """Map internal source IDs (e.g. SRC-1) to reader-friendly academic citations ([1], [2], etc.)."""
        mapping = {}
        for idx, ref in enumerate(report.references, start=1):
            num = ref.citation_number if ref.citation_number is not None else idx
            src_id_upper = ref.source_id.upper()

            clean_summary = ref.formatted_text.strip()
            if clean_summary.startswith(f"[{num}]"):
                clean_summary = clean_summary[len(f"[{num}]"):].strip()

            academic_tag = f"[{num}]"
            info = {
                "display": academic_tag,
                "number": num,
                "summary": clean_summary,
                "source_id": ref.source_id
            }
            mapping[src_id_upper] = info
            mapping[str(num)] = info

        return mapping

    @staticmethod
    def _format_single_reference_html(ref, num: int) -> str:
        """Format a single reference with italicized journals and clean, hyperlinked DOIs/URLs."""
        raw_text = ref.formatted_text.strip()
        raw_text = re.sub(r"^(?:\[\d+\]|\d+\.)\s*", "", raw_text)
        safe_text = html.escape(raw_text)
        safe_text = re.sub(r"\*([^*]+)\*", r"<i>\1</i>", safe_text)

        has_linked_doi = False
        def doi_repl(m):
            nonlocal has_linked_doi
            has_linked_doi = True
            prefix = m.group(1)
            raw_doi = m.group(2).rstrip(".")
            return f'{prefix}<a href="https://doi.org/{raw_doi}" target="_blank" rel="noopener" class="ref-url-link">https://doi.org/{raw_doi} <span class="ext-icon">↗</span></a>.'

        safe_text = re.sub(r"(DOI:\s*|doi:\s*)(10\.\d{4,9}/[^\s,<]+)", doi_repl, safe_text)
        safe_text = re.sub(
            r"(?<!href=\")(?<!\">)(https?://[^\s,<]+)",
            r'<a href="\1" target="_blank" rel="noopener" class="ref-url-link">\1 <span class="ext-icon">↗</span></a>',
            safe_text
        )

        badge_html = ""
        if not has_linked_doi and getattr(ref, "doi", None):
            clean_doi = ref.doi.strip()
            badge_html = f' <a href="https://doi.org/{clean_doi}" target="_blank" rel="noopener" class="ref-pill-btn">DOI: {clean_doi} ↗</a>'
        elif getattr(ref, "url", None) and "http" in ref.url and ref.url not in safe_text:
            badge_html = f' <a href="{html.escape(ref.url)}" target="_blank" rel="noopener" class="ref-pill-btn">Access Article ↗</a>'

        return f"""
            <li class="reference-item" id="ref-{num}">
                <span class="ref-num">[{num}]</span>
                <span class="ref-text">{safe_text}</span>{badge_html}
            </li>
        """

    @staticmethod
    def _sanitize_for_pdf(text: str) -> str:
        """Replace Unicode characters unsupported by Helvetica/Times with ASCII equivalents."""
        replacements = [
            ("\u2018", "'"), ("\u2019", "'"), ("\u201A", ","), ("\u201B", "'"),
            ("\u201C", '"'), ("\u201D", '"'), ("\u201E", '"'), ("\u201F", '"'),
            ("\u2013", "-"), ("\u2014", "-"), ("\u2015", "-"), ("\u2212", "-"),
            ("\u2026", "..."), ("\u2022", "*"), ("\u00A0", " "), ("\u2002", " "),
            ("\u2003", " "), ("\u2009", " "), ("\u202F", " "), ("\u00AE", "(R)"),
            ("\u00A9", "(c)"), ("\u2122", "TM"), ("\u2264", "<="), ("\u2265", ">="),
            ("\u2260", "!="), ("\u00B1", "+/-"), ("\u2192", "->"), ("\u2190", "<-"),
            ("\u25A0", "[*]"), ("■", "[*]"),
        ]
        for src, dst in replacements:
            text = text.replace(src, dst)
        return text.encode("latin-1", errors="replace").decode("latin-1")

    @staticmethod
    def _format_in_text_for_pdf(text: str, report: AcademicReport) -> str:
        """Sanitize Unicode, escape XML entities, and replace source tags with clean academic citations."""
        text = ReportFormatter._sanitize_for_pdf(text)
        text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        mapping = ReportFormatter._build_citation_mapping(report)

        def replace_cit(match):
            tag = match.group(1).upper()
            if tag in mapping:
                n = mapping[tag]['number']
                return f'<font color="#00629B">[{n}]</font>'
            m = re.match(r"SRC-(\d+)", tag)
            if m:
                return f'<font color="#00629B">[{m.group(1)}]</font>'
            return f'<font color="#00629B">[{tag}]</font>'

        return re.sub(r"\[(SRC-\d+|\d+)\]", replace_cit, text)

    @staticmethod
    def to_markdown(report: AcademicReport) -> str:
        """Export report as structured Markdown with clean academic citations."""
        mapping = ReportFormatter._build_citation_mapping(report)

        def clean_md_citations(content: str) -> str:
            def repl(m):
                tag = m.group(1).upper()
                if tag in mapping:
                    return mapping[tag]["display"]
                m_sub = re.match(r"SRC-(\d+)", tag)
                if m_sub:
                    return f"[{m_sub.group(1)}]"
                return f"[{tag}]"
            return re.sub(r"\[(SRC-\d+|\d+)\]", repl, content)

        lines = [
            f"# {report.title}\n",
            f"**Citation Style:** {report.citation_style.value} | **Date:** {report.created_at[:10]}\n",
            "## Abstract",
            clean_md_citations(report.abstract),
            "\n"
        ]

        if report.keywords:
            lines.append(f"**Keywords:** {', '.join(report.keywords)}\n")

        for s in report.sections:
            lines.append(f"## {s.heading}")
            lines.append(clean_md_citations(s.content))
            lines.append("\n")

        if report.conclusion:
            lines.append(f"## {len(report.sections) + 1}. Conclusion")
            lines.append(clean_md_citations(report.conclusion))
            lines.append("\n")

        lines.append("## References")
        for ref in report.references:
            lines.append(f"- {ref.formatted_text}")

        return "\n".join(lines)

