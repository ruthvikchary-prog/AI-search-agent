    @staticmethod
    def _format_ieee_heading_text(heading: str, section_idx: int) -> tuple[str, str]:
        """
        Converts any heading into authentic IEEE Access styling matching images 2, 3, 4:
        - Main section: 'I. INTRODUCTION' (returns formatted text and 'h1')
        - Subsection: 'A. MOTIVATION AND BACKGROUND' (returns formatted text and 'h2')
        - Sub-subsection: '1) CLASSICAL AGENTS' (returns formatted text and 'h3')
        """
        ROMAN_NUMS = ["I", "II", "III", "IV", "V", "VI", "VII", "VIII", "IX", "X", "XI", "XII", "XIII", "XIV", "XV"]
        raw = heading.strip()

        # Check sub-subsection: 1) CLASSICAL AGENTS or 1.1.1
        subsub_m = re.match(r"^(?:\d+\.\d+\.\d+|\d+\))\s*(.*)", raw)
        if subsub_m:
            title = subsub_m.group(1).strip()
            num_m = re.match(r"^(\d+)", raw)
            num_str = num_m.group(1) if num_m else "1"
            return f"{num_str}) {title.upper()}", "h3"

        # Check subsection: A. MOTIVATION or 1.1 MOTIVATION
        sub_m = re.match(r"^(?:[A-Z]\.|\d+\.\d+)\s*(.*)", raw)
        if sub_m:
            title = sub_m.group(1).strip()
            letter_m = re.match(r"^([A-Z])\.", raw)
            letter = letter_m.group(1) if letter_m else "A"
            return f"{letter}. {title.upper()}", "h2"

        # Check existing Roman numeral: I. INTRODUCTION
        roman_m = re.match(r"^([IVXLCDM]+)\.\s*(.*)", raw, re.IGNORECASE)
        if roman_m:
            rom = roman_m.group(1).upper()
            title = roman_m.group(2).strip()
            return f"{rom}. {title.upper()}", "h1"

        # Check Arabic numeral: 1. Introduction -> I. INTRODUCTION
        arabic_m = re.match(r"^(\d+)\.\s*(.*)", raw)
        if arabic_m:
            num = int(arabic_m.group(1))
            title = arabic_m.group(2).strip()
            rom = ROMAN_NUMS[min(num - 1, len(ROMAN_NUMS) - 1)] if num > 0 else "I"
            return f"{rom}. {title.upper()}", "h1"

        # Unnumbered: convert using section_idx
        rom = ROMAN_NUMS[min(section_idx - 1, len(ROMAN_NUMS) - 1)] if section_idx > 0 else "I"
        return f"{rom}. {raw.upper()}", "h1"

    @staticmethod
    def generate_pdf(report: AcademicReport, output_dir: Optional[Path] = None) -> Path:
        """Render a publication-quality academic PDF adhering to authentic IEEE Access format (Images 2, 3, 4)."""
        target_dir = output_dir or Config.GENERATED_FOLDER
        target_dir.mkdir(parents=True, exist_ok=True)
        filename = f"Report_{report.id[:8]}_{report.citation_style.value}.pdf"
        pdf_path = target_dir / filename

        # Guarantee IEEE Access journal two-column output for all generated papers
        return ReportFormatter._generate_ieee_access_pdf(report, pdf_path)

